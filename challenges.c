/*
  Creates smooth challenge values for testing the speedup achieved by
  the attacks against MinRoot (Biryukov et al., CRYPTO 2024).

  Parallelised with OpenMP:
	- Each challenge is generated by an independent thread with its own
	  GMP random state seeded from RANDSEED ^ (i+1).
	- Multiple challenges are generated in parallel with schedule(dynamic).
	- The modulo is generated once on the main thread before forking.

  Build:
	gcc -O2 -fopenmp challenges.c -lgmp -o challenges

  Usage: ./challenges <num_challenges> <modulo_bits> <smoothness_bound>
  Example: ./challenges 2 20480 35
*/

#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <gmp.h>

#ifdef _OPENMP
#include <omp.h>
#endif

#define RANDSEED 12380174892374ULL

void print_usage(void)
{
	printf("Usage:\n  challenges <num_challenges> <modulo_bits> <smoothness_bound>\n");
	printf("Example:\n  ./challenges 2 20480 35 \n");
}

static void generate_one_challenge(
	mpz_t result, const mpz_t modulo,
	mp_bitcnt_t bitbound, mp_bitcnt_t bittarget,
	gmp_randstate_t rstate,
	const char *factors_path, int *count_out)
{
	mpz_t temp;
	mpz_init(temp);
	FILE *f;

	f = fopen(factors_path, "w");
	if (f)
		fclose(f); /* clear */

	int count = 0;
	mpz_set_ui(result, 1);
	long threshold = (long)bittarget - (long)bitbound;
	if (threshold < 0)
		threshold = 0;

	do
	{
		mpz_urandomb(temp, rstate, bitbound);
		mpz_nextprime(temp, temp);

		if (mpz_sizeinbase(result, 2) + mpz_sizeinbase(temp, 2) >
			mpz_sizeinbase(modulo, 2))
			continue;

		f = fopen(factors_path, "ab");
		if (f)
		{
			mpz_out_raw(f, temp);
			fclose(f);
		}

		mpz_mul(result, result, temp);
		count++;
	} while ((long)mpz_sizeinbase(result, 2) < threshold);

	*count_out = count;
	mpz_clear(temp);
}

int main(int argc, char **argv)
{
	if (argc < 4)
	{
		printf("Not enough arguments!\n");
		print_usage();
		return EINVAL;
	}
	if (argc > 5)
	{
		printf("Too many arguments!\n");
		print_usage();
		return EINVAL;
	}

	unsigned int num_outputs = (unsigned int)strtoul(argv[1], NULL, 10);
	mp_bitcnt_t bittarget = (mp_bitcnt_t)strtoul(argv[2], NULL, 10);
	mp_bitcnt_t bitbound = (mp_bitcnt_t)strtoul(argv[3], NULL, 10);

	char savefolder[128];
	snprintf(savefolder, sizeof(savefolder),
			 "data/challenges/k%lu/", (unsigned long)bitbound);
	{
		char cmd[256];
		snprintf(cmd, sizeof(cmd), "mkdir -p %s", savefolder);
		if (system(cmd) != 0)
			printf("Warning: could not create %s\n", savefolder);
	}

	if (bitbound > bittarget)
		printf("Note: bitbound (%lu) > bittarget (%lu).\n",
			   (unsigned long)bitbound, (unsigned long)bittarget);

	int n_threads = 1;
#ifdef _OPENMP
	n_threads = omp_get_max_threads();
	printf("OpenMP: %d threads\n", n_threads);
#endif
	printf("Generating %u challenge(s), ~%lu bits, B=2^%lu\n\n",
		   num_outputs, (unsigned long)bittarget, (unsigned long)bitbound);

	/* ---- Modulo (single-threaded, deterministic) ---- */
	gmp_randstate_t main_rand;
	gmp_randinit_default(main_rand);
	gmp_randseed_ui(main_rand, RANDSEED);

	mpz_t modulo;
	mpz_init(modulo);
	mpz_set_ui(modulo, 1);
	mpz_mul_2exp(modulo, modulo, bittarget);
	mpz_nextprime(modulo, modulo);
	while (mpz_tdiv_ui(modulo, 3) != 2)
		mpz_nextprime(modulo, modulo);
	gmp_randclear(main_rand);

	printf("Modulo: %lu bits\n", (unsigned long)mpz_sizeinbase(modulo, 2));

	char modulo_path[256];
	snprintf(modulo_path, sizeof(modulo_path), "%smodulo_%lu_%lu.txt",
			 savefolder, (unsigned long)bitbound, (unsigned long)bittarget);
	{
		FILE *f = fopen(modulo_path, "wb");
		if (f)
		{
			mpz_out_raw(f, modulo);
			fclose(f);
		}
		printf("Wrote modulo to %s\n\n", modulo_path);
	}

	/* ---- Challenges (parallel — one per thread where possible) ---- */
	clock_t t0 = clock();

#pragma omp parallel for schedule(dynamic, 1) num_threads(n_threads) \
	shared(savefolder, modulo, bitbound, bittarget, num_outputs)
	for (int i = 0; i < (int)num_outputs; i++)
	{
		/* Each challenge gets its own deterministic random state */
		gmp_randstate_t rstate;
		gmp_randinit_default(rstate);
		gmp_randseed_ui(rstate,
						RANDSEED ^ ((unsigned long long)(i + 1) * 6364136223846793005ULL));

		char fpath[256], cpath[256];
		snprintf(fpath, sizeof(fpath), "%sfactors_%d_%lu_%lu.txt",
				 savefolder, i,
				 (unsigned long)bitbound, (unsigned long)bittarget);
		snprintf(cpath, sizeof(cpath), "%schallenge_%d_%lu_%lu.txt",
				 savefolder, i,
				 (unsigned long)bitbound, (unsigned long)bittarget);

		mpz_t result;
		mpz_init(result);
		int count = 0;
		generate_one_challenge(result, modulo, bitbound, bittarget,
							   rstate, fpath, &count);

		{
			FILE *f = fopen(cpath, "wb");
			if (f)
			{
				mpz_out_raw(f, result);
				fclose(f);
			}
		}

		/* Verify and time the baseline powm */
		mpz_t temp, exp, m1;
		mpz_inits(temp, exp, m1, NULL);
		mpz_sub_ui(m1, modulo, 1);
		mpz_set_ui(temp, 3);
		mpz_invert(exp, temp, m1);
		mpz_powm_ui(temp, result, 3, modulo);
		clock_t ts = clock();
		mpz_powm(temp, temp, exp, modulo);
		clock_t te = clock();
		double ms = 1000.0 * (double)(te - ts) / CLOCKS_PER_SEC;
		int ok = (mpz_cmp(temp, result) == 0);

#pragma omp critical
		{
			printf("[challenge %d] %lu bits, %d factors, "
				   "baseline=%.3f ms%s\n",
				   i, (unsigned long)mpz_sizeinbase(result, 2),
				   count, ms, ok ? "" : "  *** VERIFY FAILED ***");
		}

		mpz_clears(temp, exp, m1, result, NULL);
		gmp_randclear(rstate);
	}

	clock_t t1 = clock();
	printf("\nAll %u challenge(s) done in %.2f s  (wall time with %d threads)\n",
		   num_outputs, (double)(t1 - t0) / CLOCKS_PER_SEC, n_threads);

	mpz_clear(modulo);
	return 0;
}
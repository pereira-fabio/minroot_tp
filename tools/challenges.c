/*
  Creates smooth challenge values for testing the speedup achieved by
  the attacks against MinRoot (Biryukov et al., CRYPTO 2024).

  Parallelised with OpenMP:
	- Each challenge is generated by an independent thread with its own
	  GMP random state seeded from RANDSEED ^ (i+1).
	- Multiple challenges are generated in parallel with schedule(dynamic).
	- The modulo is generated once on the main thread before forking.

  Build:
	gcc -O2 -fopenmp challenges.c -lgmp -o challenges

  Usage: ./challenges <num_challenges> <modulo_bits> <smoothness_bound>
  Example: ./challenges 2 20480 35
*/

#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <gmp.h>

#ifdef _OPENMP
#include <omp.h>
#endif

#define RANDSEED 12380174892374ULL


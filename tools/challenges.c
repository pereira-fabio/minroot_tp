/*
  Creates smooth challenge values for testing the speedup achieved by
  the attacks against MinRoot (Biryukov et al., CRYPTO 2024).

  Parallelised with OpenMP:
	- Each challenge is generated by an independent thread with its own
	  GMP random state seeded from RANDSEED ^ (i+1).
	- Multiple challenges are generated in parallel with schedule(dynamic).
	- The modulo is generated once on the main thread before forking.

  Build:
	gcc -O2 -fopenmp challenges.c -lgmp -o challenges

  Usage: ./challenges <num_challenges> <modulo_bits> <smoothness_bound>
  Example: ./challenges 2 20480 35
*/

#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <gmp.h>

#ifdef _OPENMP
#include <omp.h>
#endif

#define RANDSEED 12380174892374ULL

void print_usage(void)
{
	printf("Usage:\n  challenges <num_challenges> <modulo_bits> <smoothness_bound>\n");
	printf("Example:\n  ./challenges 2 20480 35 \n");
}

static void generate_one_challenge(
	mpz_t result, const mpz_t modulo,
	mp_bitcnt_t bitbound, mp_bitcnt_t bittarget,
	gmp_randstate_t rstate,
	const char *factors_path, int *count_out)
{
	mpz_t temp;
	mpz_init(temp);

	/* Open factor file ONCE — avoids 1 fopen/fclose syscall per prime */
	FILE *f = fopen(factors_path, "wb");

	int count = 0;
	mpz_set_ui(result, 1);
	long threshold = (long)bittarget - (long)bitbound;
	if (threshold < 0)
		threshold = 0;

	do
	{
		mpz_urandomb(temp, rstate, bitbound);
		mpz_nextprime(temp, temp);

		/* Skip if product would exceed modulo */
		if (mpz_sizeinbase(result, 2) + mpz_sizeinbase(temp, 2) >
			mpz_sizeinbase(modulo, 2))
			continue;

		if (f)
			mpz_out_raw(f, temp); /* write factor — file stays open */

		mpz_mul(result, result, temp);
		count++;
	} while ((long)mpz_sizeinbase(result, 2) < threshold);

	if (f)
		fclose(f); /* close once at the end */

	*count_out = count;
	mpz_clear(temp);
}

/*
 * Parallel replacement for the sequential mpz_nextprime + mod-3 loop.
 *
 * Splits the odd-candidate stream starting at 2^bits across all OMP threads.
 * Thread tid tests candidates: base+1+2*tid, base+1+2*tid+2*nt, ...
 * (stride 2*nt keeps every candidate odd; no two threads test the same value).
 * The first thread to pass both the mod-3 filter and the Miller-Rabin test
 * writes the result and sets `found`, causing all other threads to exit.
 *
 * Speedup: ~nthreads vs single-threaded mpz_nextprime — for 24576-bit moduli,
 * this cuts several minutes down to roughly 30 s with 10 threads.
 */
static void find_prime_parallel(mpz_t result, mp_bitcnt_t bits)
{
	mpz_t base;
	mpz_init(base);
	mpz_setbit(base, bits); /* base = 2^bits; first candidate is base+1 */

	volatile int found = 0;

#pragma omp parallel shared(found, result, base)
	{
		int tid = 0, nt = 1;
#ifdef _OPENMP
		tid = omp_get_thread_num();
		nt  = omp_get_num_threads();
#endif
		mpz_t cand;
		mpz_init(cand);
		unsigned long offset = (unsigned long)(2 * tid + 1);

		while (!found) {
			mpz_add_ui(cand, base, offset);
			if(mpz_tdiv_ui(cand, 3) == 2){
				if(mpz_probab_prime_p(cand, 20) > 0){
					#pragma omp critical
					{
						if(!found){
							mpz_set(result, cand);
							found = 1;
						}
					}
				}
			}
			offset += (unsigned long)(2 * nt);
		 }

		mpz_clear(cand);
	}

	mpz_clear(base);
}

int main(int argc, char **argv)
{
	if (argc < 4)
	{
		printf("Not enough arguments!\n");
		print_usage();
		return EINVAL;
	}
	if (argc > 5)
	{
		printf("Too many arguments!\n");
		print_usage();
		return EINVAL;
	}

	unsigned int num_outputs = (unsigned int)strtoul(argv[1], NULL, 10);
	mp_bitcnt_t bittarget = (mp_bitcnt_t)strtoul(argv[2], NULL, 10);
	mp_bitcnt_t bitbound = (mp_bitcnt_t)strtoul(argv[3], NULL, 10);

	char savefolder[128];
	snprintf(savefolder, sizeof(savefolder),
			 "data/challenges/k%lu/", (unsigned long)bitbound);
	{
		char cmd[256];
		snprintf(cmd, sizeof(cmd), "mkdir -p %s", savefolder);
		if (system(cmd) != 0)
			printf("Warning: could not create %s\n", savefolder);
	}

	if (bitbound > bittarget)
		printf("Note: bitbound (%lu) > bittarget (%lu).\n",
			   (unsigned long)bitbound, (unsigned long)bittarget);

	int n_threads = 1;
#ifdef _OPENMP
	n_threads = omp_get_max_threads();
	printf("OpenMP: %d threads\n", n_threads);
#endif
	printf("Generating %u challenge(s), ~%lu bits, B=2^%lu\n\n",
		   num_outputs, (unsigned long)bittarget, (unsigned long)bitbound);

	/* ---- Modulo: load from file if it exists, generate only if missing ----
	 *
	 * mpz_nextprime on a 20480-bit number takes several minutes because it
	 * must run Miller-Rabin on ~14000 candidates.  Caching the modulo file
	 * avoids this on every re-run of the generator for the same bittarget.
	 * -------------------------------------------------------------------- */
	mpz_t modulo;
	mpz_init(modulo);

	char modulo_path[256];
	snprintf(modulo_path, sizeof(modulo_path), "%smodulo_%lu_%lu.txt",
			 savefolder, (unsigned long)bitbound, (unsigned long)bittarget);

	{
		FILE *mf = fopen(modulo_path, "rb");
		if (mf)
		{
			/* Fast path: modulo already exists — load it */
			mpz_inp_raw(modulo, mf);
			fclose(mf);
			printf("Modulo loaded from %s (%lu bits)\n\n",
				   modulo_path,
				   (unsigned long)mpz_sizeinbase(modulo, 2));
		}
		else
		{
			/* Slow path: parallel prime search (find_prime_parallel races OMP
			 * threads across odd candidates; expected speedup ≈ nthreads vs
			 * the old single-threaded mpz_nextprime loop). */
			printf("Generating %lu-bit modulo (parallel search, %d thread(s))...\n",
				   (unsigned long)bittarget, n_threads);
			fflush(stdout);

			find_prime_parallel(modulo, bittarget);

			/* Save for future runs */
			mf = fopen(modulo_path, "wb");
			if (mf)
			{
				mpz_out_raw(mf, modulo);
				fclose(mf);
			}

			printf("Modulo saved to %s (%lu bits)\n\n",
				   modulo_path,
				   (unsigned long)mpz_sizeinbase(modulo, 2));
		}
	}

	/* ---- Challenges (parallel — one per thread where possible) ---- */
#ifdef _OPENMP
	double wall_t0 = omp_get_wtime();
#else
	clock_t t0 = clock();
#endif

#pragma omp parallel for schedule(dynamic, 1) num_threads(n_threads) \
	shared(savefolder, modulo, bitbound, bittarget, num_outputs)
	for (int i = 0; i < (int)num_outputs; i++)
	{
		/* Each challenge gets its own deterministic random state */
		gmp_randstate_t rstate;
		gmp_randinit_default(rstate);
		gmp_randseed_ui(rstate,
						RANDSEED ^ ((unsigned long long)(i + 1) * 6364136223846793005ULL));

		char fpath[256], cpath[256];
		snprintf(fpath, sizeof(fpath), "%sfactors_%d_%lu_%lu.txt",
				 savefolder, i,
				 (unsigned long)bitbound, (unsigned long)bittarget);
		snprintf(cpath, sizeof(cpath), "%schallenge_%d_%lu_%lu.txt",
				 savefolder, i,
				 (unsigned long)bitbound, (unsigned long)bittarget);

		mpz_t result;
		mpz_init(result);
		int count = 0;
		generate_one_challenge(result, modulo, bitbound, bittarget,
							   rstate, fpath, &count);

		{
			FILE *f = fopen(cpath, "wb");
			if (f)
			{
				mpz_out_raw(f, result);
				fclose(f);
			}
		}

		/* Verify and time the baseline powm */
		mpz_t temp, exp, m1;
		mpz_inits(temp, exp, m1, NULL);
		mpz_sub_ui(m1, modulo, 1);
		mpz_set_ui(temp, 3);
		mpz_invert(exp, temp, m1);
		mpz_powm_ui(temp, result, 3, modulo);
#ifdef _OPENMP
		double ts = omp_get_wtime();
		mpz_powm(temp, temp, exp, modulo);
		double ms = (omp_get_wtime() - ts) * 1000.0;
#else
		clock_t ts = clock();
		mpz_powm(temp, temp, exp, modulo);
		double ms = 1000.0 * (double)(clock() - ts) / CLOCKS_PER_SEC;
#endif
		int ok = (mpz_cmp(temp, result) == 0);

#pragma omp critical
		{
			printf("[challenge %d] %lu bits, %d factors, "
				   "baseline=%.3f ms%s\n",
				   i, (unsigned long)mpz_sizeinbase(result, 2),
				   count, ms, ok ? "" : "  *** VERIFY FAILED ***");
		}

		mpz_clears(temp, exp, m1, result, NULL);
		gmp_randclear(rstate);
	}

#ifdef _OPENMP
	printf("\nAll %u challenge(s) done in %.2f s  (wall clock, %d threads)\n",
		   num_outputs, omp_get_wtime() - wall_t0, n_threads);
#else
	clock_t t1 = clock();
	printf("\nAll %u challenge(s) done in %.2f s\n",
		   num_outputs, (double)(t1 - t0) / CLOCKS_PER_SEC);
#endif

	mpz_clear(modulo);
	return 0;
}